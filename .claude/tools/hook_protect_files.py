#!/usr/bin/env python3
"""PreToolUse hook for Edit and Write: ask before changing files that look fixable but aren't.

A few files in this repository must stay as they are (a deliberately sloppy CI
fixture, generated assets, text kept verbatim). The hook asks the user instead of
refusing, because a maintainer sometimes does need to change them.
"""

from __future__ import annotations

import fnmatch
import sys
from pathlib import Path

from devenv import pre_tool_decision, read_event, repo_root, same_repository

# Project-relative POSIX glob -> why the file should not be edited casually.
PROTECTED_FILES = {
    ".github/action-fixture/*": (
        "this fixture is sloppy on purpose: CI scans it and asserts the exact findings "
        "(see .github/workflows/action.yml)"
    ),
    "docs/demo.gif": "the GIF is generated by docs/demo/record.sh, not edited by hand",
    "CODE_OF_CONDUCT.md": "this is the upstream Contributor Covenant text, kept verbatim",
    "LICENSE": "the licence text must not change",
}


def protection_reason(path: Path, event: dict) -> str | None:
    """Why ``path`` is protected, or None if it can be edited freely."""
    root = repo_root(path.parent)
    if root is None or not same_repository(root, event):
        return None
    try:
        relative = path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return None
    for pattern, why in PROTECTED_FILES.items():
        if fnmatch.fnmatchcase(relative, pattern):
            return f"{relative}: {why}."
    return None


def main() -> int:
    """Turn an edit of a protected file into a question for the user."""
    event = read_event()
    tool_input = event.get("tool_input")
    file_path = tool_input.get("file_path") if isinstance(tool_input, dict) else None
    if isinstance(file_path, str) and file_path:
        reason = protection_reason(Path(file_path), event)
        if reason:
            pre_tool_decision("ask", reason)
    return 0


if __name__ == "__main__":
    sys.exit(main())
